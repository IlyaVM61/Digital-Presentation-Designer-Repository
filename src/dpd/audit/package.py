"""Чтение выгруженного `.pptx` для проверок, работающих по файлу.

**Вопрос «файл не открывается» принадлежит одной проверке.** Её
идентификатор — `integrity.file_broken`, и она о нём сообщает. Остальным
файловым проверкам на нечитаемом файле сказать нечего: растровый слайд в нём
не найти и пропорции картинок не измерить.

Без этого разделения битый файл роняет весь прогон: первая же проверка,
открывшая пакет, выбрасывает исключение, и отчёта не появляется вовсе — в том
числе находки о том, что файл сломан. Получалось бы, что самый тяжёлый дефект
единственный, о котором система промолчать обязана.

Исключение при этом не подавляется молча: его текст возвращается вызывающему
и попадает в находку `integrity.file_broken` как доказательство.
"""

from __future__ import annotations

from pathlib import Path

from pptx import Presentation
from pptx.presentation import Presentation as PresentationType


def read_package(pptx_path: str | Path) -> tuple[PresentationType | None, str | None]:
    """Открыть презентацию. Вернуть её либо причину, по которой не удалось.

    Ловится любая ошибка, а не заранее перечисленные: «файл не открывается» —
    это и есть любая причина, по которой его не удалось прочитать, от
    повреждённого архива до отсутствующей части пакета. Перечислять причины
    заранее значило бы пропустить неучтённую.

    Отсутствие файла ошибкой пакета не считается и поднимается наверх: это
    ошибка прогона, а не дефект колоды.
    """
    pptx_path = Path(pptx_path)
    if not pptx_path.is_file():
        raise FileNotFoundError(f"файл не найден: {pptx_path}")

    try:
        presentation = Presentation(str(pptx_path))
        # Обращение к слайдам обязательно: часть ошибок пакета проявляется
        # только при чтении содержимого, а не при открытии.
        list(presentation.slides)
    except Exception as error:  # noqa: BLE001 — важна не причина, а сам факт
        return None, f"{type(error).__name__}: {error}"[:200]
    return presentation, None
